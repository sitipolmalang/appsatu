defmodule Appsatu.Blog do
  @moduledoc """
  The Blog context.
  """

  import Ecto.Query, warn: false
  alias Appsatu.Repo

  alias Appsatu.Blog.Post

  @doc """
  Returns the list of posts.

  ## Examples

      iex> list_posts()
      [%Post{}, ...]

  """
  def list_posts do
    Repo.all(Post)
    |> Repo.preload([:category, :tags, :images, :user])
  end

  @doc """
  Returns the list of posts for a specific user.
  """
  def list_user_posts(user_id) do
    Repo.all(from p in Post, where: p.user_id == ^user_id)
    |> Repo.preload([:category, :tags, :images, :user])
  end

  @doc """
  Checks if a user owns a post.
  """
  def user_owns_post?(%Post{} = post, user_id), do: post.user_id == user_id

  @doc """
  Gets a single post for a specific user (with authorization).
  Returns nil if post doesn't exist or doesn't belong to user.
  """
  def get_user_post!(user_id, post_id) do
    Repo.get!(Post, post_id)
    |> Repo.preload([:category, :tags, :images, :user])
    |> case do
      %{user_id: ^user_id} = post -> post
      _ -> raise Ecto.NoResultsError
    end
  rescue
    Ecto.NoResultsError -> nil
  end

  @doc """
  Gets a single post.

  Raises `Ecto.NoResultsError` if the Post does not exist.

  ## Examples

      iex> get_post!(123)
      %Post{}

      iex> get_post!(456)
      ** (Ecto.NoResultsError)

  """
  def get_post!(id) do
    Repo.get!(Post, id)
    |> Repo.preload([:category, :tags, :images, :user])
  end

  @doc """
  Creates a post.

  ## Examples

      iex> create_post(%{field: value})
      {:ok, %Post{}}

      iex> create_post(%{field: bad_value})
      {:error, %Ecto.Changeset{}}

  """
  def create_post(attrs) do
    %Post{}
    |> Post.changeset(attrs)
    |> Repo.insert()
  end

  @doc """
  Updates a post.

  ## Examples

      iex> update_post(post, %{field: new_value})
      {:ok, %Post{}}

      iex> update_post(post, %{field: bad_value})
      {:error, %Ecto.Changeset{}}

  """
  def update_post(%Post{} = post, attrs) do
    post
    |> Post.changeset(attrs)
    |> Repo.update()
  end

  @doc """
  Deletes a post.

  ## Examples

      iex> delete_post(post)
      {:ok, %Post{}}

      iex> delete_post(post)
      {:error, %Ecto.Changeset{}}

  """
  def delete_post(%Post{} = post) do
    Repo.delete(post)
  end

  @doc """
  Returns an `%Ecto.Changeset{}` for tracking post changes.

  ## Examples

      iex> change_post(post)
      %Ecto.Changeset{data: %Post{}}

  """
  def change_post(%Post{} = post, attrs \\ %{}) do
    Post.changeset(post, attrs)
  end

  alias Appsatu.Blog.PostImage

  def create_post_image(attrs) do
    %PostImage{}
    |> PostImage.changeset(attrs)
    |> Repo.insert()
  end

  def list_post_images(post_id) do
    Repo.all(from(image in PostImage, where: image.post_id == ^post_id))
  end

  def get_post_image(id), do: Repo.get(PostImage, id)
  def get_post_image!(id), do: Repo.get!(PostImage, id)

  def delete_post_image(%PostImage{} = image) do
    Repo.delete(image)
  end

  def delete_post_images(post_id, roles) when is_list(roles) do
    from(image in PostImage, where: image.post_id == ^post_id and image.role in ^roles)
    |> Repo.all()
    |> Enum.each(&Repo.delete!/1)
  end

  def delete_post_images_by_ids(ids) when is_list(ids) do
    from(image in PostImage, where: image.id in ^ids)
    |> Repo.delete_all()
  end

